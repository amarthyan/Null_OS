// Persistent state manager
import { DeveloperAPI } from './developerAPI.js';
import { UselessnessEngine } from './uselessnessEngine.js';
import { AchievementEngine } from './achievementEngine.js';

class StoreManager {
  constructor() {
    this.storageKey = 'nullos_installed_apps';
    this.ratingsKey = 'nullos_user_ratings';
    this.scoreKey = 'nullos_uselessness_score';
    this.installed = this.loadInstalled();
    this.ratings = this.loadRatings();
    this.score = this.loadScore();
    this.listeners = new Set();

    // Listen for custom app registrations
    DeveloperAPI.subscribe(() => {
      this.notify();
    });
  }

  loadInstalled() {
    try {
      const saved = localStorage.getItem(this.storageKey);
      if (saved) return new Set(JSON.parse(saved));
    } catch (e) {}
    // Default installed apps
    return new Set(['rockSimulator', 'button']);
  }

  saveInstalled() {
    try {
      localStorage.setItem(this.storageKey, JSON.stringify([...this.installed]));
    } catch (e) {}
  }

  loadRatings() {
    try {
      const saved = localStorage.getItem(this.ratingsKey);
      if (saved) return JSON.parse(saved);
    } catch (e) {}
    return {};
  }

  saveRatings() {
    try {
      localStorage.setItem(this.ratingsKey, JSON.stringify(this.ratings));
    } catch (e) {}
  }

  loadScore() {
    try {
      const saved = localStorage.getItem(this.scoreKey);
      if (saved) return parseInt(saved, 10);
    } catch (e) {}
    return 1420;
  }

  saveScore() {
    try {
      localStorage.setItem(this.scoreKey, String(this.score));
    } catch (e) {}
  }

  addScore(pts) {
    this.score += pts;
    this.saveScore();
    this.notify();
  }

  isInstalled(id) {
    return this.installed.has(id);
  }

  installApp(id) {
    this.installed.add(id);
    this.saveInstalled();
    this.addScore(250);
    UselessnessEngine.recordAppInstall(id);
    AchievementEngine.setProgress('storage-destroyer', this.installed.size);
    this.notify();
  }

  uninstallApp(id) {
    this.installed.delete(id);
    this.saveInstalled();
    this.addScore(100);
    UselessnessEngine.recordAppUninstall(id);
    this.notify();
  }

  rateApp(id, stars) {
    this.ratings[id] = stars;
    this.saveRatings();
    this.addScore(50);
    UselessnessEngine.recordRating();
    this.notify();
  }

  getUserRating(id) {
    return this.ratings[id] || null;
  }

  subscribe(listener) {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  notify() {
    this.listeners.forEach(cb => cb());
  }

  getRank() {
    if (this.score > 10000) return 'Grand Master of Nothing';
    if (this.score > 5000) return 'Senior Idler';
    if (this.score > 2500) return 'Certified Void Explorer';
    return 'Apprentice of Uselessness';
  }
}

export const StoreState = new StoreManager();

/**
 * Returns all available apps combining standard catalog and dynamically registered apps.
 */
export function getMergedAppCatalog() {
  const custom = DeveloperAPI.getCustomApps();
  const map = new Map();
  AppCatalog.forEach(a => map.set(a.id, a));
  custom.forEach(a => map.set(a.id, a));
  return Array.from(map.values());
}

